#!/usr/bin/env python3
"""Build-time only: convert the few decorative glyphs the share card draws (verdict words, seal text)
to SVG path data, so the card never depends on fonts installed on the viewer's machine.

  pip install fonttools
  python3 scripts/gen-glyphs.py <fonts-dir>   # writes src/report/glyphs.ts

Fonts (all SIL OFL 1.1):
  ZCOOLQingKeHuangYou-Regular.ttf  https://github.com/google/fonts/tree/main/ofl/zcoolqingkehuangyou  (seal)
  NotoSansCJK-Bold.ttc / NotoSerifCJK-Bold.ttc (SC face)  https://github.com/notofonts/noto-cjk
  InterDisplay-Black.otf / InterDisplay-ExtraBold.otf      https://github.com/rsms/inter
Coordinates: 1000 units per em, y down. CJK glyphs sit in a 1000×1000 box (top = 0);
Latin glyphs have the baseline at y = 0 and carry their advance width.
"""
import os, sys, json
from fontTools.ttLib import TTFont, TTCollection
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

D = sys.argv[1] if len(sys.argv) > 1 else 'fonts'
SYS = '/usr/share/fonts/opentype'

def load(path, face='SC'):
    if path.endswith('.ttc'):
        for f in TTCollection(path).fonts:
            if face in f['name'].getDebugName(1):
                return f
    return TTFont(path)

def num(v):
    s = '%.0f' % v
    return '0' if s == '-0' else s

def outline(f, ch, dy=0.0):
    upm = f['head'].unitsPerEm
    gs = f.getGlyphSet()
    name = f.getBestCmap()[ord(ch)]
    s = 1000 / upm
    pen = SVGPathPen(gs, ntos=num)
    gs[name].draw(TransformPen(pen, (s, 0, 0, -s, 0, dy)))
    bp = BoundsPen(gs)
    gs[name].draw(bp)
    return pen.getCommands(), gs[name].width * s, bp.bounds

def cjk(path, chars):
    f = load(path)
    # place the font's ideographic em box (ascent from OS/2 typo metrics) at y 0..1000
    os2 = f['OS/2']
    upm = f['head'].unitsPerEm
    asc = os2.sTypoAscender * 1000 / upm
    desc = -os2.sTypoDescender * 1000 / upm
    top = asc - (1000 - (asc + desc)) / 2 if asc + desc != 1000 else asc
    out = {}
    for ch in chars:
        d, _, _ = outline(f, ch, dy=top)
        out[ch] = d
    return out

def latin(path, chars):
    f = load(path)
    out = {}
    for ch in chars:
        d, adv, _ = outline(f, ch)
        out[ch] = {'d': d, 'w': round(adv)}
    return out

SEAL = cjk(f'{D}/ZCOOLQingKeHuangYou-Regular.ttf', '一致不存疑验货')
HEI = cjk(f'{SYS}/noto/NotoSansCJK-Bold.ttc', '一致不存疑')
SONG = cjk(f'{SYS}/noto/NotoSerifCJK-Bold.ttc', '一致不存疑验货')
CAPS = latin(f'{SYS}/inter/InterDisplay-Black.otf', 'ACDEHIKLNOPRSTUVY')

ts = [
    '// Generated by scripts/gen-glyphs.py; do not edit. Glyph outlines (SIL OFL 1.1 fonts:',
    '// ZCOOL QingKe HuangYou, Noto Sans/Serif CJK SC, Inter Display) so the card needs no installed fonts.',
    '/* eslint-disable */',
    '/** CJK glyphs in a 1000×1000 box, y down. */',
    f'export const SEAL_GLYPHS: Record<string, string> = {json.dumps(SEAL, ensure_ascii=False)};',
    f'export const HEI_GLYPHS: Record<string, string> = {json.dumps(HEI, ensure_ascii=False)};',
    f'export const SONG_GLYPHS: Record<string, string> = {json.dumps(SONG, ensure_ascii=False)};',
    '/** Latin caps, baseline at y = 0, with advance widths (Inter Display Black, cap height ≈ 727). */',
    f'export const CAPS_GLYPHS: Record<string, {{ d: string; w: number }}> = {json.dumps(CAPS)};',
    '',
]
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'report', 'glyphs.ts'), 'w').write('\n'.join(ts))
print('ok', {k: sum(len(v) if isinstance(v, str) else len(v['d']) for v in g.values()) for k, g in [('seal', SEAL), ('hei', HEI), ('song', SONG), ('caps', CAPS)]})
